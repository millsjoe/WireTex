#!/usr/bin/env node
/**
 * Sync lib/generator/prompts/wiretex-generator.txt into:
 * - lib/generator/system-prompt.generated.ts (importable SYSTEM_PROMPT constant)
 * - models/Modelfile (Ollama custom model)
 *
 * Usage: node scripts/sync-system-prompt.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const promptPath = join(root, "lib/generator/prompts/wiretex-generator.txt");
const prompt = readFileSync(promptPath, "utf-8").trim();

if (!prompt) {
  console.error("Prompt file is empty:", promptPath);
  process.exit(1);
}

writeFileSync(
  join(root, "lib/generator/system-prompt.generated.ts"),
  [
    "// Auto-generated by scripts/sync-system-prompt.mjs — do not edit by hand.",
    "// Edit lib/generator/prompts/wiretex-generator.txt, then run: npm run sync-system-prompt",
    "",
    `export const SYSTEM_PROMPT = ${JSON.stringify(prompt)};`,
    "",
  ].join("\n"),
);

writeFileSync(
  join(root, "models/Modelfile"),
  [
    "FROM qwen3.5:9b",
    "",
    "PARAMETER temperature 0.3",
    "PARAMETER top_p 0.9",
    "PARAMETER num_predict 2048",
    "",
    'SYSTEM """',
    prompt,
    '"""',
    "",
  ].join("\n"),
);

console.log(
  "Synced system prompt to lib/generator/system-prompt.generated.ts and models/Modelfile",
);
console.log(
  "NOTE: The prompt used by the deployed WireTexAI backend lives in the WireTexAI repo at internal/prompt/wiretex-generator.txt.",
);
console.log(
  "To update production: edit that file, run scripts/generate-modelfile.sh, rebuild the wiretex-generator Ollama model, and rebuild the Docker image.",
);
